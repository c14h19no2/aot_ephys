function info = assessDisplayTiming(ifi,samples,stddev,windowInfo,debugFallback)
%ASSESSDISPLAYTIMING Describe IFI provenance without certifying photons.
% Sample count / stddev from finalized external display sinks are placeholders
% in PTB's GetFlipInterval implementation, not calibration statistics.
if nargin<4, windowInfo=struct(); end
if nargin<5, debugFallback=false; end
assert(isnumeric(ifi) && isscalar(ifi) && isfinite(ifi) && ifi>0, ...
    'ephys:InvalidRefreshInterval','PTB scheduling requires a finite positive IFI.');
finalizedSink = hasFlag(windowInfo,'ImagingMode',2^20);
externalBackend = finalizedSink || hasFlag(windowInfo,'SpecialFlags',2^32);
info = struct('ifi_source',"unverified_ptb_estimate", ...
    'scheduling_ifi_s',ifi,'reported_samples',samples, ...
    'reported_stddev_s',stddev,'external_display_backend',externalBackend, ...
    'finalized_fbo_sink',finalizedSink,'interval_is_measured',false, ...
    'sample_statistics_applicable',false, ...
    'sample_statistics_status',"unavailable", ...
    'reference_min_samples',50,'reference_max_stddev_s',0.001, ...
    'missed_deadline_flag_applicable',~externalBackend, ...
    'physical_timestamp_validation',"not independently verified", ...
    'warning_message',"");
if debugFallback
    info.ifi_source = "configured_debug_fallback";
    info.sample_statistics_status = "not_measured_debug";
elseif finalizedSink
    info.ifi_source = "external_backend_reported";
    info.sample_statistics_status = "not_applicable_external_backend";
    info.warning_message = sprintf([ ...
        'External display backend reports IFI %.9f s (%.3f Hz). ' ...
        'GetFlipInterval sample count/stddev are not calibration statistics ' ...
        'for this backend. Continuing with per-flip logs; physical timestamp ' ...
        'accuracy remains unverified.'],ifi,1/ifi);
else
    info.sample_statistics_applicable = true;
    info.interval_is_measured = isscalar(samples) && isfinite(samples) && ...
        samples>=2 && isscalar(stddev) && isfinite(stddev) && stddev>=0;
    if info.interval_is_measured, info.ifi_source="measured"; end
    acceptable = info.interval_is_measured && ...
        samples>=info.reference_min_samples && stddev<=info.reference_max_stddev_s;
    if acceptable
        info.sample_statistics_status = "within_reference_limits";
    else
        info.sample_statistics_status = "outside_reference_limits";
        info.warning_message = sprintf([ ...
            'PTB reports IFI %.9f s with %g samples and stddev %.6f s. ' ...
            'Calibration statistics are outside the diagnostic reference ' ...
            'limits; continuing with per-flip logs. Review observed frame ' ...
            'intervals and playback QC.'],ifi,samples,stddev);
    end
end
end

function present = hasFlag(info,field,flag)
present = isstruct(info) && isfield(info,field) && ...
    isnumeric(info.(field)) && isscalar(info.(field)) && ...
    isfinite(info.(field)) && info.(field)>=0 && ...
    bitand(uint64(info.(field)),uint64(flag))~=0;
end
