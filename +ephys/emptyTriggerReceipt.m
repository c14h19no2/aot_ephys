    'qc_only_failure',false,'cancel_request_getsecs',NaN, ...
    'cancellation_status',"",'status',"queued",'error',"", ...
    'waveform_file',"",'waveform_sha256',"", ...
    'source_sample_rate_hz',NaN,'output_sample_rate_hz',NaN, ...
    'waveform_samples',NaN,'pulse_width_s',NaN,'output_channel',NaN);
end
