function fit = fitClockMapping(markers,verifiedTTL,maxResidualS)
%FITCLOCKMAPPING Fit an independently verified trigger clock to the PTB clock.
% Correspondence must be independently verified by event_id. Repeated
% waveform events alone do not identify individual markers.
if nargin < 3, maxResidualS = NaN; end
if istable(markers), markers = table2struct(markers); end
if istable(verifiedTTL), verifiedTTL = table2struct(verifiedTTL); end
assert(numel(markers)>=3 && numel(verifiedTTL)>=3, ...
    'ephys:ClockAnchors','At least three matched events are required.');
if isfield(markers,'status')
    assert(~any(string({markers.status})=="dummy") && ...
        ~any(string({markers.status})=="failed"), ...
        'ephys:ClockSoftwareOnly', ...
        'Dummy or failed software markers cannot establish a physical clock fit.');
end
required = {'event_id','ephys_time_s','verified'};
assert(all(isfield(verifiedTTL,required)),'ephys:ClockCorrespondence', ...
    'External correspondence requires ID, time, and verified status.');
softwareIds = string({markers.event_id});
ttlIds = string({verifiedTTL.event_id});
assert(numel(unique(softwareIds))==numel(softwareIds) && ...
    numel(unique(ttlIds))==numel(ttlIds), ...
    'ephys:ClockDuplicate','Duplicate marker correspondence ID.');
assert(all([verifiedTTL.verified]),'ephys:ClockUnverified', ...
    'All clock anchors require independently verified correspondence.');
assert(numel(markers)==numel(verifiedTTL) && ...
    all(ismember(softwareIds,ttlIds)), 'ephys:ClockMissing', ...
    'Clock fit requires a complete one-to-one set of anchors.');
[~,loc] = ismember(softwareIds,ttlIds);
ttl = verifiedTTL(loc);
if isfield(markers,'code') && isfield(ttl,'code')
    % Preserve readback of independently verified historical numeric markers.
    assert(all([markers.code]==[ttl.code]),'ephys:ClockCode', ...
        'Historical matched trigger code differs from the software record.');
    x=[markers.request_getsecs]';
    mappingClock="historical software marker request GetSecs to recording clock";
else
    if isfield(markers,'status')
        assert(all(string({markers.status})=="complete"), ...
            'ephys:ClockSoftwareOnly', ...
            'Named WAV clock anchors must be completed outputs, not pending or cancelled reservations.');
    end
    assert(isfield(markers,'trigger_key') && isfield(ttl,'trigger_key') && ...
        all(string({markers.trigger_key})==string({ttl.trigger_key})), ...
        'ephys:ClockTrigger','Matched waveform trigger identity differs.');
    if isfield(ttl,'waveform_file')
        assert(all(string({markers.waveform_file})==string({ttl.waveform_file})), ...
            'ephys:ClockTrigger','Matched waveform file differs.');
    end
    assert(isfield(markers,'audio_start_getsecs'), ...
        'ephys:ClockAudioTime','Named WAV anchors require reported audio start times.');
    x=[markers.audio_start_getsecs]';
    mappingClock="PTB reported audio start GetSecs to recording clock";
end
y = [ttl.ephys_time_s]';
assert(all(isfinite(x)) && all(isfinite(y)) && ...
    all(diff(x)>0) && all(diff(y)>0), 'ephys:ClockOrder', ...
    'Anchors must be finite and strictly ordered in both clocks.');
x0 = mean(x); y0 = mean(y);
b = sum((x-x0).*(y-y0))/sum((x-x0).^2);
a = y0-b*x0;
residual = y-(a+b*x);
rmse = sqrt(mean(residual.^2));
residualSE = sqrt(sum(residual.^2)/(numel(x)-2));
fit = struct('offset_s',a,'clock_rate',b, ...
    'relative_drift_ppm',(b-1)*1e6,'anchor_count',numel(x), ...
    'event_ids',softwareIds,'residual_s',residual, ...
    'rmse_s',rmse,'max_abs_residual_s',max(abs(residual)), ...
    'residual_standard_error_s',residualSE, ...
    'mapping_clock',mappingClock, ...
    'visual_alignment',"requires independently measured audio output and photodiode latency", ...
    'acceptance_threshold_s',maxResidualS,'within_threshold',NaN);
if isfinite(maxResidualS)
    assert(maxResidualS>0,'ephys:ClockThreshold', ...
        'Acceptance threshold must be positive.');
    fit.within_threshold = max(abs(residual))<=maxResidualS;
end
end
