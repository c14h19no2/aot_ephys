function waves=loadTriggerWaveforms(markers)
%LOADTRIGGERWAVEFORMS Route unchanged pulse samples to the configured output.
settings=markers.wav;
assert(isfield(settings,'output_channel') && isnumeric(settings.output_channel) && ...
    isreal(settings.output_channel) && isscalar(settings.output_channel) && ...
    any(settings.output_channel==[1 2]), ...
    'ephys:TriggerAudioChannel','markers.wav.output_channel must be 1 (left) or 2 (right).');
directory=char(settings.directory);
if ~startsWith(directory,filesep)
    directory=fullfile(ephys.projectRoot(),directory);
end
keys=["run_start","run_end","video_onset","video_offset"];
waves=struct('trigger_key',{},'file',{},'path',{},'sha256',{}, ...
    'data',{},'source_sample_rate_hz',{},'output_sample_rate_hz',{}, ...
    'samples',{},'duration_s',{},'output_channel',{});
for k=1:numel(keys)
    file=string(markers.waveforms.(keys(k)));
    path=fullfile(directory,char(file));
    assert(isfile(path),'ephys:TriggerWaveform','Trigger waveform does not exist: %s',path);
    info=audioinfo(path); [data,rate]=audioread(path);
    assert(isequal(size(data),[100,2]) && all(isfinite(data(:))) && ...
        info.BitsPerSample==16,'ephys:TriggerWaveform', ...
        'Trigger waveform must contain the original 100 stereo PCM16 samples: %s',path);
    assert(settings.channels==2 && settings.sample_rate_hz==48000, ...
        'ephys:TriggerWaveform','Original trigger pulses require stereo output at 48000 Hz.');
    assert(all(data(:,2)==0) && all(data(:,1)==data(1,1)) && data(1,1)~=0, ...
        'ephys:TriggerWaveform','Source WAV must contain a constant left-channel pulse with a silent right channel: %s',path);
    routed=zeros(2,size(data,1));
    routed(settings.output_channel,:)=data(:,1).';
    waves(k)=struct('trigger_key',keys(k),'file',file,'path',string(path), ...
        'sha256',string(ephys.sha256(path)),'data',routed, ...
        'source_sample_rate_hz',rate,'output_sample_rate_hz',settings.sample_rate_hz, ...
        'samples',size(data,1),'duration_s',size(data,1)/settings.sample_rate_hz, ...
        'output_channel',settings.output_channel);
end
amplitude=arrayfun(@(w) w.data(w.output_channel,1),waves);
assert(amplitude(1)>0 && amplitude(2)<0 && amplitude(3)>0 && amplitude(4)<0 && ...
    amplitude(1)==-amplitude(2) && amplitude(3)==-amplitude(4) && amplitude(3)>amplitude(1), ...
    'ephys:TriggerWaveform','Trigger pulses must have distinct positive/negative low and high amplitude pairs.');
assert(numel(unique(amplitude))==4,'ephys:TriggerWaveform','The four waveforms must contain distinct sample data.');
assert(numel(unique(string({waves.file})))==numel(keys), ...
    'ephys:TriggerWaveform','The four event waveforms must use distinct files.');
end
