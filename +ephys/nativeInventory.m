function inventory=nativeInventory(inventory,playback)
%NATIVEINVENTORY Validate native maps and copies before opening the PTB window.
% File bytes are not hashed here: verify_aot_ephys_media compares the original
% and the native copy with the SHA-256 values recorded in the map.
folder=ephys.nativeMediaRoot(playback);
for k=1:numel(inventory)
    if inventory(k).kind~="video", continue; end
    [~,stem]=fileparts(inventory(k).name);
    path=fullfile(folder,stem+".json");
    assert(isfile(path),'ephys:NativeMediaMissing', ...
        ['Native map missing for %s. Copy its prepared MP4 and JSON into ' ...
        'playback.native_media_root, or run prepare_aot_ephys_native_media on a preparation computer.'],inventory(k).name);
    map=jsondecode(fileread(path));
    required={'schema_version','lossless_yuv_equal','pts_equal','source','source_sha256', ...
        'sha256','frame_count','source_pts_s','relative_pts_s','decoded_yuv_md5', ...
        'width_px','height_px','duration_s'};
    assert(isstruct(map) && isscalar(map) && all(isfield(map,required)), ...
        'ephys:NativeMap','Invalid verified native map: %s',path);
    assert(isequal(map.schema_version,1) && isequal(map.lossless_yuv_equal,true) && ...
        isequal(map.pts_equal,true) && positiveScalar(map.frame_count) && ...
        map.frame_count==floor(map.frame_count) && ...
        positiveScalar(map.width_px) && map.width_px==floor(map.width_px) && ...
        positiveScalar(map.height_px) && map.height_px==floor(map.height_px) && ...
        positiveScalar(map.duration_s) && ...
        isnumeric(map.source_pts_s) && isvector(map.source_pts_s) && ...
        all(isfinite(map.source_pts_s(:))) && ...
        isnumeric(map.relative_pts_s) && isvector(map.relative_pts_s) && ...
        all(isfinite(map.relative_pts_s(:))) && ...
        map.frame_count==numel(map.source_pts_s) && ...
        map.frame_count==numel(map.relative_pts_s) && ...
        map.frame_count==numel(map.decoded_yuv_md5), ...
        'ephys:NativeMap','Invalid verified native map: %s',path);
    map.conversion_source=map.source;
    map.source=char(inventory(k).path);
    map.path=char(fullfile(folder,inventory(k).name));
    assert(abs(map.relative_pts_s(1))<=1e-6 && ...
        all(diff(map.relative_pts_s)>0) && ...
        all(abs(map.relative_pts_s(:)-(map.source_pts_s(:)-map.source_pts_s(1)))<=1e-6) && ...
        map.relative_pts_s(end)<map.duration_s, ...
        'ephys:NativeMap','Invalid verified native map: %s',path);
    % Older callers may supply independently probed source metadata. Retain
    % those checks; the native runtime leaves these fields unpopulated.
    for field=["width_px","height_px"]
        assert(~isfinite(inventory(k).(field)) || inventory(k).(field)==map.(field), ...
            'ephys:NativeMap','Native/source dimensions disagree: %s',path);
    end
    assert(~isfinite(inventory(k).duration_s) || ...
        map.duration_s+1e-6>=inventory(k).duration_s, ...
        'ephys:NativeMap','Native copy is shorter than its original.');
    assert(isfile(map.path),'ephys:NativeMediaMissing', ...
        ['Native video missing: %s. Copy it with its JSON map, or run ' ...
        'prepare_aot_ephys_native_media on a preparation computer.'],map.path);
    inventory(k).width_px=map.width_px;
    inventory(k).height_px=map.height_px;
    inventory(k).duration_s=map.duration_s;
    % Descriptive average only; frame delivery/scheduling use exact mapped PTS.
    inventory(k).fps=map.frame_count/map.duration_s;
    inventory(k).source_pts_s=map.source_pts_s(:)';
    inventory(k).native_path=string(map.path);
    inventory(k).native_map_path=string(path);
    inventory(k).native_map=map;
end
end

function valid=positiveScalar(value)
valid=isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && value>0;
end
