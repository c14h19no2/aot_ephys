function folder=nativeMediaRoot(playback,field)
%NATIVEMEDIAROOT Require an explicitly configured native-copy directory.
% field is the playback setting to read: native_media_root (default) or
% practice_native_media_root.
if nargin<2, field='native_media_root'; end
message=sprintf(['Set playback.%s to the native-copy folder in your ' ...
    'config/site YAML. Missing, empty, null or none values are not allowed; ' ...
    'there is no default folder.'],field);
assert(isfield(playback,field) && ...
    (ischar(playback.(field)) || isstring(playback.(field))), ...
    'ephys:NativeMediaRoot','%s',message);
folder=strtrim(string(playback.(field)));
assert(isscalar(folder) && ~ismissing(folder) && strlength(folder)>0 && ...
    ~any(strcmpi(folder,["none","null","~"])), ...
    'ephys:NativeMediaRoot','%s',message);
end
