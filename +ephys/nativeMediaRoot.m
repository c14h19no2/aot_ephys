function folder=nativeMediaRoot(playback)
%NATIVEMEDIAROOT Require an explicitly configured native-copy directory.
message=['Set playback.native_media_root to the native-copy folder in your ' ...
    'config/site YAML. Missing, empty, null or none values are not allowed; ' ...
    'there is no default folder.'];
assert(isfield(playback,'native_media_root') && ...
    (ischar(playback.native_media_root) || isstring(playback.native_media_root)), ...
    'ephys:NativeMediaRoot','%s',message);
folder=strtrim(string(playback.native_media_root));
assert(isscalar(folder) && ~ismissing(folder) && strlength(folder)>0 && ...
    ~any(strcmpi(folder,["none","null","~"])), ...
    'ephys:NativeMediaRoot','%s',message);
end
