function map = parseDecodedFrames(logText,rawBytes)
%PARSEDECODEDFRAMES Bind raw RGB frame order to PTS from the same decoder pass.
tb = regexp(logText,'config in time_base:\s*(\d+)/(\d+)','tokens','once');
assert(~isempty(tb),'ephys:FrameMap','Decoder did not report its time base.');
numerator=str2double(tb{1}); denominator=str2double(tb{2});
assert(numerator>0 && denominator>0,'ephys:FrameMap','Invalid time base.');
rows = regexp(logText, ...
    'n:\s*(\d+)\s+pts:\s*(-?\d+)\s+pts_time:[^\r\n]*?fmt:rgb24[^\r\n]*?s:(\d+)x(\d+)[^\r\n]*?checksum:([0-9A-Fa-f]+)', ...
    'tokens');
assert(~isempty(rows),'ephys:FrameMap','No decoded RGB frame records.');
count=numel(rows); indices=zeros(count,1); ticks=zeros(count,1);
width=zeros(count,1); height=zeros(count,1); checksums=strings(count,1);
for k=1:count
    r=rows{k}; indices(k)=str2double(r{1}); ticks(k)=str2double(r{2});
    width(k)=str2double(r{3}); height(k)=str2double(r{4}); checksums(k)=string(r{5});
end
assert(isequal(indices,(0:count-1)') && all(isfinite(ticks)) && ...
    all(abs(ticks)<flintmax) && all(diff(ticks)>0), ...
    'ephys:FrameMap','Frame indices or PTS are missing, duplicated, or out of order.');
assert(all(width==width(1)) && all(height==height(1)) && ...
    width(1)>0 && height(1)>0,'ephys:FrameMap','Frame dimensions changed.');
assert(rawBytes==count*width(1)*height(1)*3,'ephys:FrameMap', ...
    'Raw RGB byte count does not match decoded frame records.');
pts=ticks*numerator/denominator;
map=struct('source_frame_index',indices,'source_pts_ticks',ticks, ...
    'time_base_numerator',numerator,'time_base_denominator',denominator, ...
    'source_pts_s',pts,'relative_pts_s',pts-pts(1), ...
    'rgb_adler32',checksums,'frame_count',count,'width_px',width(1), ...
    'height_px',height(1),'pixel_format','rgb24');
end
