function meta = probeMovie(path,playback)
%PROBEMOVIE Read encoded stream metadata; never derive frame identity from FPS.
raw = ephys.runMediaProcess({playback.ffprobe_path,'-v','error', ...
    '-select_streams','v:0','-show_entries', ...
    'stream=width,height,duration,start_time,avg_frame_rate,nb_frames', ...
    '-of','json',char(path)});
data = jsondecode(raw);
assert(isfield(data,'streams') && numel(data.streams)==1, ...
    'ephys:MovieMetadata','Expected one selected video stream: %s',path);
s = data.streams;
rate = sscanf(s.avg_frame_rate,'%f/%f');
assert(numel(rate)==2 && all(isfinite(rate)) && all(rate>0), ...
    'ephys:MovieMetadata','Invalid average frame rate: %s',path);
meta = struct('width',double(s.width),'height',double(s.height), ...
    'duration',str2double(s.duration),'fps',rate(1)/rate(2));
assert(isfinite(meta.duration) && meta.duration>0, ...
    'ephys:MovieMetadata','Missing video stream duration: %s',path);
end
