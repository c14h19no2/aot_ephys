function validateConfig(c)
%VALIDATECONFIG Fail preflight on missing protocol, assets, or unsafe options.
assert(any(string(c.playback.backend)==["native","frames"]), ...
    'ephys:PlaybackBackend','playback.backend must be native or frames.');
assert(validDuration(c.playback.native_buffer_s,false) && ...
    c.playback.native_buffer_s>=c.protocol.video_duration_s && ...
    validDuration(c.playback.native_prepare_timeout_s,false), ...
    'ephys:NativeBuffer','Native buffer must cover a complete video slot, with a positive preparation timeout.');
assert(islogical(c.playback.native_disable_hw_decode) && ...
    isscalar(c.playback.native_disable_hw_decode), ...
    'ephys:NativeDecoder','native_disable_hw_decode must be a YAML boolean.');
assert(isnumeric(c.playback.max_texture_bytes) && ...
    isscalar(c.playback.max_texture_bytes) && ...
    isfinite(c.playback.max_texture_bytes) && c.playback.max_texture_bytes>0, ...
    'ephys:TextureBudget','playback.max_texture_bytes must be positive.');
assert(isnumeric(c.playback.startup_preload_movies) && ...
    isscalar(c.playback.startup_preload_movies) && ...
    isfinite(c.playback.startup_preload_movies) && ...
    c.playback.startup_preload_movies>=0 && ...
    c.playback.startup_preload_movies==floor(c.playback.startup_preload_movies), ...
    'ephys:StartupPreload','playback.startup_preload_movies must be a nonnegative integer.');
assert(string(c.playback.backend)~="native" || ...
    any(c.playback.startup_preload_movies==[1 2]), ...
    'ephys:NativeStartup','Native playback needs 1 or 2 startup movie handles.');
assert(strcmp(string(c.task.name),"aot_ephys"),'ephys:TaskProfile', ...
    'Only the AOT electrophysiology profile is implemented.');
assert(any(c.task_kind == ["video","memory"]),'ephys:TaskKind', ...
    'Task must be video or memory.');
if c.task_kind=="video" && string(c.playback.backend)=="native"
    ephys.nativeMediaRoot(c.playback);
end
assert(c.debug || isequal(c.protocol.approved_for_acquisition,true), ...
    'ephys:ProtocolApproval', ...
    ['Non-debug run blocked: %s has protocol.approved_for_acquisition: false. ' ...
    'Keep it false until the site approves timing, display, fixation, and trigger setup. ' ...
    'Use Debug=true with an explicit Schedule to check movie playback.'], ...
    char(c.site_path));
if c.task_kind == "video"
    p = c.protocol;
    assert(string(c.playback.backend)~="native" || p.video_pre_fixation_s>0, ...
        'ephys:NativePreFixation','Native lookahead requires a positive pre-fixation interval.');
    assert(validDuration(p.video_initial_fixation_s,true) && ...
        validDuration(p.video_final_fixation_s,true), ...
        'ephys:RunFixation', ...
        'Initial/final video fixation durations must be finite and nonnegative.');
    assert(validDuration(p.video_pre_fixation_s,true) && ...
        validDuration(p.video_duration_s,false) && ...
        validDuration(p.video_post_fixation_s,true), ...
        'ephys:VideoProtocol', ...
        'Set finite pre, video, and post durations in config/experiment.yml.');
end
assert(iscell(c.display.resolution_px) && numel(c.display.resolution_px)==2, ...
    'ephys:Display','Display resolution must have two values.');
resolution = cell2mat(c.display.resolution_px);
assert(all(isfinite(resolution)) && all(resolution>0) && ...
    all(resolution==floor(resolution)) && ...
    isscalar(c.display.expected_refresh_hz) && ...
    c.display.expected_refresh_hz>0, ...
    'ephys:Display','Invalid display dimensions or refresh.');
assert(c.debug || ~c.display.skip_sync_tests, ...
    'ephys:SkipSyncAcquisition','PTB sync checks are mandatory in acquisition.');
if isfield(c.display,'refresh_guard_min_fraction')
    guard = c.display.refresh_guard_min_fraction;
    assert(isempty(guard) || (isnumeric(guard) && isreal(guard) && ...
        isscalar(guard) && isfinite(guard) && guard>0 && guard<=1), ...
        'ephys:RefreshGuardConfig', ...
        'display.refresh_guard_min_fraction must be null or a fraction in (0,1].');
end
if isfield(c.display,'steady_flip')
    assert(islogical(c.display.steady_flip) && isscalar(c.display.steady_flip), ...
        'ephys:SteadyFlipConfig','display.steady_flip must be true or false.');
end
assert(isscalar(c.instructions.text_height_px) && ...
    c.instructions.text_height_px>=1 && ...
    c.instructions.text_height_px==floor(c.instructions.text_height_px), ...
    'ephys:TextSize','PTB text size must be a positive integer.');
assert(isnumeric(c.stimulus.movie_scale) && ...
    isscalar(c.stimulus.movie_scale) && ...
    isreal(c.stimulus.movie_scale) && isfinite(c.stimulus.movie_scale) && ...
    c.stimulus.movie_scale>0 && c.stimulus.movie_scale<=1, ...
    'ephys:MovieGeometry','movie_scale must be a finite scalar in (0,1].');
% Raises ephys:ScreenSize or ephys:TargetSize for invalid values; null is allowed.
ephys.viewingDistance(c);
keys = string({c.input.instruction_continue_key, ...
    c.input.memory_yes_key,c.input.memory_no_key,c.input.quit_key});
assert(all(strlength(keys)>0) && numel(unique(lower(keys)))==numel(keys), ...
    'ephys:InputKeys','Instruction, memory, and quit keys must be distinct.');
fix = c.stimulus.fixation;
angles = {fix.surround_diameter_deg,fix.dot_diameter_deg,fix.line_width_deg};
assert(all(cellfun(@(v) validDuration(v,false) && v<10,angles)) && ...
    validDuration(fix.surround_fringe,true) && fix.surround_fringe<=1 && ...
    validDuration(fix.outline_width_deg,true) && ...
    fix.outline_width_deg<fix.dot_diameter_deg, ...
    'ephys:FixationGeometry', ...
    ['stimulus.fixation needs positive sizes in degrees, surround_fringe ' ...
    'between 0 and 1 and an outline from 0 up to the dot size.']);
% Pixel sizes come from stimulus.target_size_deg, which must then be set.
ephys.fixationGeometry(c);
markers=c.markers;
assert(~any(isfield(markers,{'codes','profile','pulse'})), ...
    'ephys:LegacyTriggerConfig', ...
    'Integer marker codes and the former TTL profile are unsupported; configure named WAV events.');
assert(validText(markers.backend) && ...
    any(string(markers.backend)==["wav","dummy"]), ...
    'ephys:BackendSelection','markers.backend must be wav or dummy.');
assert(validText(markers.memory_backend) && ...
    string(markers.memory_backend)=="dummy", ...
    'ephys:MemoryTriggerBackend', ...
    'Memory events require memory_backend: dummy until a memory waveform protocol is configured.');
for field=["memory_onset_enabled","run_boundary_enabled","blank_enabled", ...
        "video_offset_enabled","fixation_onset_enabled"]
    assert(islogical(markers.(field)) && isscalar(markers.(field)), ...
        'ephys:TriggerSwitch','Marker switches must be YAML booleans.');
end
keys=["run_start","run_end","video_onset","video_offset"];
assert(isstruct(markers.waveforms) && isscalar(markers.waveforms) && ...
    isequal(sort(string(fieldnames(markers.waveforms))),sort(keys(:))), ...
    'ephys:TriggerWaveform','Configure exactly the four named video/run WAV events.');
for key=keys
    filename=markers.waveforms.(key);
    assert(validText(filename) && strlength(string(filename))>0 && ...
        endsWith(lower(string(filename)),".wav") && ...
        ~contains(string(filename),["/","\"]), ...
        'ephys:TriggerWaveform','Each waveform must be a WAV filename within markers.wav.directory.');
end
wav=markers.wav;
assert(validText(wav.directory) && strlength(strtrim(string(wav.directory)))>0 && ...
    ~any(lower(strtrim(string(wav.directory)))==["none","null","~"]), ...
    'ephys:TriggerWaveDirectory','markers.wav.directory must name the trigger asset folder.');
assert(isempty(wav.device_index) || (isnumeric(wav.device_index) && ...
    isscalar(wav.device_index) && isfinite(wav.device_index) && ...
    wav.device_index>=0 && wav.device_index==floor(wav.device_index)), ...
    'ephys:TriggerAudioDevice','Audio device_index must be null or a nonnegative integer.');
assert(validText(wav.device_name),'ephys:TriggerAudioDevice', ...
    'Audio device_name must be a scalar string, or empty for no name constraint.');
assert(isequal(wav.sample_rate_hz,48000) && isequal(wav.channels,2), ...
    'ephys:TriggerAudioFormat', ...
    'The trigger protocol requires two channels at 48000 Hz, without waveform resampling.');
assert(isnumeric(wav.output_channel) && isreal(wav.output_channel) && ...
    isscalar(wav.output_channel) && any(wav.output_channel==[1 2]), ...
    'ephys:TriggerAudioChannel','markers.wav.output_channel must be 1 (left) or 2 (right).');
assert(isnumeric(wav.gain) && isscalar(wav.gain) && isfinite(wav.gain) && ...
    wav.gain>0 && wav.gain<=1, ...
    'ephys:TriggerAudioGain','Audio gain must be greater than 0 and at most 1.');
assert(isnumeric(wav.latency_class) && isscalar(wav.latency_class) && ...
    isfinite(wav.latency_class) && any(wav.latency_class==0:4), ...
    'ephys:TriggerAudioLatency','Audio latency_class must be an integer from 0 through 4.');
for field=["minimum_lead_s","minimum_low_s","completion_timeout_s","max_sync_error_s"]
    assert(validDuration(wav.(field),false),'ephys:TriggerAudioTiming', ...
        'Audio lead, low time, completion timeout, and sync tolerance must be finite and positive.');
end
% Read the original samples here; no audio device is opened during config preflight.
ephys.loadTriggerWaveforms(markers);
if c.task_kind=="video" && string(markers.backend)=="wav"
    assert(~markers.fixation_onset_enabled,'ephys:TriggerWaveEvent', ...
        'WAV fixation markers have no waveform assignment; keep fixation_onset_enabled false.');
    leadWithMargin=wav.minimum_lead_s+2/c.display.expected_refresh_hz;
    assert(c.protocol.video_pre_fixation_s>=leadWithMargin, ...
        'ephys:TriggerLead','Pre-fixation must provide the WAV lead plus two drawing refresh intervals.');
    if markers.run_boundary_enabled && c.protocol.video_final_fixation_s>0
        assert(c.protocol.video_final_fixation_s>=leadWithMargin, ...
            'ephys:TriggerLead','Final fixation must provide the WAV lead plus two drawing refresh intervals.');
    end
    if markers.video_offset_enabled
        pulseAndLow=100/wav.sample_rate_hz+wav.minimum_low_s;
        assert(c.protocol.video_duration_s>=max(pulseAndLow,leadWithMargin) && ...
            c.protocol.video_post_fixation_s+c.protocol.video_pre_fixation_s>=pulseAndLow, ...
            'ephys:TriggerSpacing', ...
            'Video boundaries must leave time for the 100-sample waveform and minimum low interval.');
    end
end
for field = {'max_flips','max_events','max_markers'}
    value = c.logging.(field{1});
    assert(isnumeric(value) && isscalar(value) && isfinite(value) && ...
        value>=1 && value==floor(value),'ephys:LogCapacity', ...
        'Invalid logging capacity.');
end
assert(strlength(string(c.paths.output_root))>0,'ephys:OutputRoot', ...
    'Output root is required.');
for i = 1:numel(c.schedule)
    assert(ephys.condition(c.schedule(i))~="unknown", ...
        'ephys:Condition','Scheduled asset has no recognized direction: %s', ...
        c.schedule(i));
end
if c.task_kind == "video" && any(c.schedule ~= "blank")
    assert(strlength(string(c.paths.video_root))>0,'ephys:VideoRoot', ...
        'Video root is required.');
    paths = fullfile(string(c.paths.video_root),c.schedule);
    assert(all(isfile(paths(c.schedule~="blank"))), ...
        'ephys:MissingVideo','One or more scheduled videos are missing.');
elseif c.task_kind == "memory"
    assert(strlength(string(c.paths.picture_root))>0,'ephys:PictureRoot', ...
        'Picture root is required.');
    paths = fullfile(string(c.paths.picture_root),c.schedule);
    assert(all(isfile(paths)),'ephys:MissingPicture', ...
        'One or more scheduled pictures are missing.');
end
if c.photodiode.enabled
    assert(c.photodiode.approved_placement,'ephys:PhotodiodeApproval', ...
        'Photodiode rectangle requires site approval.');
    assert(iscell(c.photodiode.rect_px) && numel(c.photodiode.rect_px)==4, ...
        'ephys:PhotodiodeRect','Set a four-value corner rectangle.');
    rect = cell2mat(c.photodiode.rect_px); rect = rect(:)';
    w=resolution(1); h=resolution(2);
    assert(all(isfinite(rect)) && all(rect==floor(rect)) && ...
        rect(1)>=0 && rect(2)>=0 && rect(3)<=w && rect(4)<=h && ...
        rect(3)>rect(1) && rect(4)>rect(2), ...
        'ephys:PhotodiodeRect','Photodiode rectangle is outside display.');
    % Overlap with each fitted stimulus is checked by mediaInventory before
    % opening PTB, once actual source dimensions are available.
    onColor = cell2mat(c.photodiode.on_rgb255);
    offColor = cell2mat(c.photodiode.off_rgb255);
    assert(numel(onColor)==3 && numel(offColor)==3 && ...
        all(onColor>=0 & onColor<=255) && ...
        all(offColor>=0 & offColor<=255) && ...
        any(onColor~=offColor), 'ephys:PhotodiodeColor', ...
        'Photodiode on/off RGB values must differ within 0 to 255.');
    if c.task_kind=="video" && c.photodiode.fixation_onset_enabled
        assert(c.protocol.video_pre_fixation_s >= ...
            2/c.display.expected_refresh_hz, ...
            'ephys:PhotodiodeFixationPulse', ...
            'Fixation photodiode pulse needs at least two refreshes.');
    end
end
end

function yes = validDuration(value,allowZero)
yes = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    (value>0 || (allowZero && value==0));
end

function yes=validText(value)
yes=(ischar(value) && (isrow(value) || isempty(value))) || ...
    (isstring(value) && isscalar(value) && ~ismissing(value));
end
